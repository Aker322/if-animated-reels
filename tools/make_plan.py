#!/usr/bin/env python3
"""Merge word timings and the creative plan into plan.js for the engine.
usage: python3 make_plan.py words.json plan.json > plan.js"""
import sys, json
words = json.load(open(sys.argv[1]))
plan = json.load(open(sys.argv[2])) if len(sys.argv) > 2 else {}
end = plan.get('end')
tail = (end.get('hold', 2.0) if end else 0.6)
dur = words['duration'] + tail
if end and 'from' not in end: end['from'] = words['duration'] + 0.05
print('// generated by make_plan.py')
print('const WORDS = ' + json.dumps(words['words']) + ';')
print(f'const DUR = {dur:.3f};')
print('const PLAN = ' + json.dumps(plan, indent=1) + ';')
